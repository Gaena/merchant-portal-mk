package az.millikart.ecom.service;

import java.util.List;

/**
 * Откуда берётся список терминалов провайдера.
 *
 * Отдельным интерфейсом, потому что это единственное место, которое зависит от формы их данных:
 * запрос к схеме шлюза здесь ещё не окончательный и будет заменён на присланный провайдером.
 * Всё, что вокруг — правила гашения, подтверждение пропаданием, сверка с нашими терминалами —
 * от этой формы не зависит и переписываться вместе с запросом не должно.
 */
public interface ProviderTerminalSource {

    /**
     * Активные терминалы провайдера.
     *
     * Контракт: вернуть **полный** список либо бросить исключение. Частичный ответ здесь
     * недопустим — вызывающий считает отсутствие терминала в списке признаком того, что тот
     * выключен, и оборванная выборка означала бы массовое гашение живых терминалов.
     */
    List<ProviderTerminalRow> fetchActive();

    /** Строка выгрузки: то, что провайдер знает о своём терминале. */
    record ProviderTerminalRow(String rid, String title, String login) {
    }
}
