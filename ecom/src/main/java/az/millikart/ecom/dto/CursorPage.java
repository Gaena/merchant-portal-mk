package az.millikart.ecom.dto;

import java.util.List;

/**
 * Страница выписки с курсором вместо номера.
 *
 * Смещение (`OFFSET`) по операционной базе шлюза не годится дважды: чем дальше страница, тем
 * дороже запрос, а строки между запросами приезжают новые, и «следующая страница» пропускает
 * или повторяет платежи. Курсор — это пара «время последней операции, номер заказа» последней
 * отданной строки; он же задаёт единственный допустимый порядок сортировки.
 *
 * `nextCursor` пуст, когда страница последняя. Общего числа строк здесь нет намеренно: `COUNT(*)`
 * по всему периоду — это второй тяжёлый запрос к боевому шлюзу ради цифры, которую показывает
 * блок статистики.
 */
public record CursorPage<T>(
        List<T> content,
        String nextCursor
) {
}
