package az.millikart.pbl.domain;

// Может ли терминал брать новые платежи. Колонка живёт в terminals — таблице, которой владеет
// directory, а этот модуль её только читает. BLOCKED останавливает лишь НОВЫЕ платежи (Р-38):
// открытие и создание ссылки отвергаются, а опрос статуса, списание DMS и возвраты по уже
// прошедшим платежам работают — проверка статуса в них заперла бы деньги плательщика на карте.
public enum TerminalStatus {
    ACTIVE,
    BLOCKED
}
