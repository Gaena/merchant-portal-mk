package az.millikart.directory.domain;

/**
 * Кто последним менял статус терминала.
 *
 * Без этого различия правило «решение клиента не трогаем» неисполнимо: в таблице виден только
 * сам статус, а «выключен человеком» и «выключен синхронизацией» требуют разного обращения.
 *
 *   MANUAL   — статус поставил человек. Выключенный так терминал не включает никто и никогда:
 *              это решение клиента, и провайдеру о нём знать не надо.
 *   PROVIDER — статус поставила синхронизация. Такой терминал она же и вернёт в строй, когда
 *              провайдер вернёт его себе, — иначе одно временное отключение на их стороне
 *              оставляло бы наш терминал мёртвым навсегда, а его ссылки приостановленными.
 */
public enum TerminalStatusSource {
    MANUAL,
    PROVIDER
}
